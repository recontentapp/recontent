import { escapeString, formatTree, setTreeValue } from "../../../../ts-source.js";
import type { SourceTree } from "../../../../ts-source.js";
import type { ConvertedToken } from "./layers.js";
import type { ThemeAxisEmit, ThemeContext } from "./themes.js";

export type EmitInput = {
  files: string[];
  ref: ConvertedToken[];
  system: ConvertedToken[];
  axes: ThemeAxisEmit[];
};

function tokenSource({ token, expr }: ConvertedToken, withMetadata: boolean): string {
  let source = expr;
  if (!withMetadata) return source;
  if (token.description !== undefined) source += `.describe('${escapeString(token.description)}')`;
  if (token.deprecated === true) source += ".deprecate()";
  else if (typeof token.deprecated === "string") {
    source += `.deprecate('${escapeString(token.deprecated)}')`;
  }
  return source;
}

function buildTree(tokens: ConvertedToken[], withMetadata: boolean): SourceTree {
  const tree: SourceTree = Object.create(null) as SourceTree;
  for (const entry of tokens) {
    setTreeValue(tree, entry.token.path, {
      value: tokenSource(entry, withMetadata),
      source: true,
    });
  }
  return tree;
}

function contextSource(theme: ThemeContext, indent: string): string {
  const layerIndent = `${indent}    `;
  const layers = (["ref", "system"] as const).flatMap((layer) => {
    const overrides = theme.overrides.filter((entry) => entry.layer === layer);
    return overrides.length === 0
      ? []
      : [`${layerIndent}${layer}: ${formatTree(buildTree(overrides, false), layerIndent)},`];
  });
  return `${indent}${JSON.stringify(theme.name)}: defineTheme(\n${indent}  { ref, system },\n${indent}  {\n${layers.join("\n")}\n${indent}  },\n${indent}),`;
}

function axisNeedsHelper(axis: ThemeAxisEmit): boolean {
  return axis.default !== "default" || axis.description !== undefined;
}

function axisSource(axis: ThemeAxisEmit): string {
  if (!axisNeedsHelper(axis)) {
    const contexts = axis.contexts.map((ctx) => contextSource(ctx, "      ")).join("\n");
    return `    ${JSON.stringify(axis.name)}: {\n${contexts}\n    },`;
  }

  const contexts = axis.contexts.map((ctx) => contextSource(ctx, "        ")).join("\n");
  const fields = [
    ...(axis.default !== "default" ? [`      default: '${escapeString(axis.default)}',`] : []),
    ...(axis.description !== undefined
      ? [`      description: '${escapeString(axis.description)}',`]
      : []),
    `      contexts: {\n${contexts}\n      },`,
  ];
  return `    ${JSON.stringify(axis.name)}: defineThemeAxis({\n${fields.join("\n")}\n    }),`;
}

export function emitConfig({ files, ref, system, axes }: EmitInput): string {
  const refSource = formatTree(buildTree(ref, true));
  const systemSource = formatTree(buildTree(system, true));
  const body = `${refSource}\n${systemSource}`;

  const isFlatImplicit =
    axes.length === 1 && axes[0]!.name === "theme" && !axisNeedsHelper(axes[0]!);
  const needsDefineThemeAxis = !isFlatImplicit && axes.some(axisNeedsHelper);

  const imports = [
    "defineReferenceTokens",
    "defineSystemTokens",
    "defineConfig",
    ...(axes.length > 0 ? ["defineTheme"] : []),
    ...(needsDefineThemeAxis ? ["defineThemeAxis"] : []),
    ...(/\btokens\./.test(body) ? ["tokens"] : []),
  ];

  let themesSource = "";
  if (axes.length > 0) {
    const entries = isFlatImplicit
      ? axes[0]!.contexts.map((ctx) => contextSource(ctx, "    ")).join("\n")
      : axes.map(axisSource).join("\n");
    themesSource = `  themes: {\n${entries}\n  },\n`;
  }

  return `// Generated by \`recontent init --dtcg\` from:
${files.map((file) => `//   - ${escapeString(file)}`).join("\n")}
import {
${imports.map((name) => `  ${name},`).join("\n")}
} from "recontent";

const ref = defineReferenceTokens(${refSource});

const system = defineSystemTokens(${systemSource});

export default defineConfig({
  tokens: {
    ref,
    system,
  },
${themesSource}});
`;
}
