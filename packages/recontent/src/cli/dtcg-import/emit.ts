import { escapeString, formatTree, setTreeValue } from "../../plugins/shared/ts-source.js";
import type { SourceTree } from "../../plugins/shared/ts-source.js";
import type { ConvertedToken } from "./layers.js";
import type { Theme } from "./themes.js";

export type EmitInput = {
  files: string[];
  ref: ConvertedToken[];
  system: ConvertedToken[];
  themes: Theme[];
};

function tokenSource({ token, expr }: ConvertedToken, withMetadata: boolean): string {
  let source = expr;
  if (!withMetadata) return source;
  if (token.description !== undefined) source += `.describe('${escapeString(token.description)}')`;
  if (token.deprecated === true) source += ".deprecate()";
  else if (typeof token.deprecated === "string") {
    source += `.deprecate('${escapeString(token.deprecated)}')`;
  }
  return source;
}

function buildTree(tokens: ConvertedToken[], withMetadata: boolean): SourceTree {
  const tree: SourceTree = Object.create(null) as SourceTree;
  for (const entry of tokens) {
    setTreeValue(tree, entry.token.path, {
      value: tokenSource(entry, withMetadata),
      source: true,
    });
  }
  return tree;
}

function themeSource(theme: Theme): string {
  const layers = (["ref", "system"] as const).flatMap((layer) => {
    const overrides = theme.overrides.filter((entry) => entry.layer === layer);
    return overrides.length === 0
      ? []
      : [`        ${layer}: ${formatTree(buildTree(overrides, false), "        ")},`];
  });
  return `    ${JSON.stringify(theme.name)}: defineTheme(
      { ref, system },
      {
${layers.join("\n")}
      },
    ),`;
}

/** Renders the `recontent.config.ts` text for the converted tokens and themes. */
export function emitConfig({ files, ref, system, themes }: EmitInput): string {
  const refSource = formatTree(buildTree(ref, true));
  const systemSource = formatTree(buildTree(system, true));
  const body = `${refSource}\n${systemSource}`;

  const imports = [
    "defineReferenceTokens",
    "defineSystemTokens",
    "defineComponentTokens",
    "defineConfig",
    ...(themes.length > 0 ? ["defineTheme"] : []),
    ...(/\btokens\./.test(body) ? ["tokens"] : []),
  ];
  const themesSource =
    themes.length > 0 ? `  themes: {\n${themes.map(themeSource).join("\n")}\n  },\n` : "";

  return `// Generated by \`recontent init --from\` from:
${files.map((file) => `//   - ${escapeString(file)}`).join("\n")}
import {
${imports.map((name) => `  ${name},`).join("\n")}
} from "recontent";

const ref = defineReferenceTokens(${refSource});

const system = defineSystemTokens(${systemSource});

const components = defineComponentTokens({});

export default defineConfig({
  tokens: {
    ref,
    system,
    components,
  },
${themesSource}});
`;
}
